    function handleTier2Reset() {
        const isTier1Visible = !q(".ab-nav-menu-container--show");

        const isTier2Visible = !!(
            q(".ab-nav-menu-container--show") &&
            q(".ab-nav-menu-container-level-2.ab-nav-menu-container--show") &&
            !q(".ab-nav-menu-container-level-2.ab-nav-menu-container--show  .ab-nav-menu-container--show")
        );

        const expandedTier2TitleElement = q(".ab-nav-menu-container-level-2.ab-nav-menu-container--show > .ab-nav-menu-header .ab-nav-menu-back-cta__text");
        const expandedTier2Title = expandedTier2TitleElement ? expandedTier2TitleElement.textContent.trim() : "";

        if (isTier1Visible || (isTier2Visible && expandedTier2Title !== defaultBrand.title)) {
            const visibleNavContainer = q(".ab-nav-menu-container--show");
            if (visibleNavContainer) visibleNavContainer.classList.remove("ab-nav-menu-container--show");
            q(`a.ab-nav-menu-item-link[href="${defaultBrand.link}"] ~ .ab-nav-menu-container-level-2`).classList.add("ab-nav-menu-container--show");
        }
    }

    function clickFunction() {
        q(".ab-nav-container").addEventListener("click", (e) => {
            const closeButton = e.target.closest(".ab-nav-close-cta");
            if (closeButton) {
                q(".close-button button.close").click();
                handleTier2Reset();
            }

            const subMenuLinkExpandable = e.target.closest(".ab-nav-menu-item-link.ab-nav-menu-item-link--has-sub-menu");
            if (subMenuLinkExpandable) {
                e.preventDefault();
                const siblingDropdownMenu = subMenuLinkExpandable.nextElementSibling;
                siblingDropdownMenu.classList.add("ab-nav-menu-container--show");
            }

            const backToParentCta = e.target.closest("button.ab-nav-menu-back-cta");
            if (backToParentCta) {
                const parentDropdownMenu = backToParentCta.parentElement.parentElement;
                parentDropdownMenu.classList.remove("ab-nav-menu-container--show");
            }
        });
    }

    // Prevent Scroll
    function preventScroll(e) {
        if (e.target.closest("nav .main-menu.in")) return;
        e.preventDefault();
    }

    function enableScroll() {
        // Enable Scrolling
        document.removeEventListener("wheel", preventScroll);
        document.removeEventListener("touchmove", preventScroll);
    }

    function disableScroll() {
        // Disable Scrolling
        document.addEventListener("wheel", preventScroll, { passive: false });
        document.addEventListener("touchmove", preventScroll, { passive: false });
    }

    function addOrRemoveScrollHander() {
        if (q("nav .main-menu.in")) {
            disableScroll();
        } else {
            enableScroll();
        }
    }

    function mutationObserverFunction() {
        const targetNode = q("nav .main-menu");
        const debouncedUpdate = debounce(addOrRemoveScrollHander, 250);
        return new MutationObserver(debouncedUpdate).observe(targetNode, { childList: false, subtree: false, attributes: true });
    }

